import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { parseSkillMarkdown, validateSkillsData } from '../plugins/vite-plugin-skills/parser'
import { PillarId } from '../src/types'
import { SkillData } from '../src/types/skills'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')
const skillsDir = path.resolve(rootDir, 'skills')
const dataDir = path.resolve(rootDir, 'src', 'data')

const RESEARCH_SKILL_DIRS: PillarId[] = [
  'product-strategic-research',
  'product-market-research',
  'product-user-research',
  'product-technical-research',
  'product-behavioral-research',
  'product-ethics-research',
]

function main() {
  console.log('⚡ Parsing SKILL.md files into structured TypeScript data...\n')

  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true })
  }

  const loadedSkills: SkillData[] = []

  for (const skillId of RESEARCH_SKILL_DIRS) {
    const filePath = path.join(skillsDir, skillId, 'SKILL.md')

    if (!fs.existsSync(filePath)) {
      console.warn(`⚠️ Warning: SKILL.md not found at ${filePath}`)
      continue
    }

    const content = fs.readFileSync(filePath, 'utf-8')
    const parsed = parseSkillMarkdown(content, skillId)
    loadedSkills.push(parsed)
  }

  // Sort by pillarNumber
  loadedSkills.sort((a, b) => a.pillarNumber - b.pillarNumber)

  // Validate
  const validation = validateSkillsData(loadedSkills)

  console.log('┌────┬──────────────────────────────────┬────────┬────────────┬──────────────┐')
  console.log('│ #  │ Pillar Skill ID                  │ Lenses │ Frameworks │ Template Wds │')
  console.log('├────┼──────────────────────────────────┼────────┼────────────┼──────────────┤')

  for (const skill of loadedSkills) {
    const num = `0${skill.pillarNumber}`
    const id = skill.id.padEnd(32)
    const lenses = String(skill.lenses.length).padStart(6)
    const frameworks = String(skill.frameworks.length).padStart(10)
    const words = String(skill.promptTemplate.split(/\s+/).length).padStart(12)
    console.log(`│ ${num} │ ${id} │ ${lenses} │ ${frameworks} │ ${words} │`)
  }

  console.log('└────┴──────────────────────────────────┴────────┴────────────┴──────────────┘')
  console.log(`\nTotal Research Skills: ${loadedSkills.length}`)
  console.log(`Total Research Lenses: ${validation.totalLenses}`)
  console.log(`Total Frameworks:      ${validation.totalFrameworks}`)

  if (validation.warnings.length > 0) {
    console.log('\nWarnings:')
    for (const w of validation.warnings) {
      console.warn(` - ${w}`)
    }
  }

  if (!validation.isValid) {
    console.error('\n❌ Validation errors detected:')
    for (const err of validation.errors) {
      console.error(` - ${err}`)
    }
    process.exit(1)
  }

  // 1. Output src/data/skills.json
  const jsonPath = path.join(dataDir, 'skills.json')
  fs.writeFileSync(jsonPath, JSON.stringify(loadedSkills, null, 2), 'utf-8')
  console.log(`\n✅ Generated JSON: ${path.relative(rootDir, jsonPath)}`)

  // 2. Output src/data/skills.ts
  const tsContent = `// Automatically generated by scripts/parse-skills.ts — DO NOT EDIT DIRECTLY
import { SkillData } from '../types/skills'
import rawSkillsData from './skills.json'

export const skillsData: SkillData[] = rawSkillsData as SkillData[]
export default skillsData

export function getSkillByPillarNumber(pillarNumber: number): SkillData | undefined {
  return skillsData.find((s) => s.pillarNumber === pillarNumber)
}

export function getSkillById(id: string): SkillData | undefined {
  return skillsData.find((s) => s.id === id)
}
`
  const tsPath = path.join(dataDir, 'skills.ts')
  fs.writeFileSync(tsPath, tsContent, 'utf-8')
  console.log(`✅ Generated TypeScript Module: ${path.relative(rootDir, tsPath)}`)
  console.log('\n✨ Skills data pipeline execution successful!\n')
}

main()
